#!/usr/bin/env node
/* Build a self-contained Prism bundle from a PrismJS source checkout.
 * Usage: node build_prism.js <prism-src-dir> <out-dir>
 * Resolves component dependencies from components.js (same approach as
 * MacDown's runtime loader), then concatenates the minified components. */
const fs = require('fs');
const path = require('path');

const prismDir = process.argv[2];
const outDir = process.argv[3];
if (!prismDir || !outDir) {
  console.error('usage: build_prism.js <prism-src-dir> <out-dir>');
  process.exit(1);
}

const componentsSrc = fs.readFileSync(path.join(prismDir, 'components.js'), 'utf8');
const components = new Function(componentsSrc + '\nreturn components;')();

const WANTED = [
  'bash','c','cpp','csharp','dart','diff','django','docker','elixir','erb',
  'git','go','graphql','haml','handlebars','haskell','http','ini','java','json',
  'json5','jsonp','jsx','tsx','kotlin','latex','less','lua','makefile','markdown',
  'matlab','nginx','nix','objectivec','perl','php','powershell','protobuf','python',
  'r','regex','ruby','rust','sass','scala','scss','sql','swift','toml','typescript',
  'vim','wasm','yaml','applescript','awk','cmake','csv','log','properties','tcl','zig'
];

const resolved = [];
const seen = new Set();
function resolve(name) {
  if (seen.has(name)) return;
  seen.add(name);
  if (name === 'core') { resolved.push('core'); return; }   // core lives outside .languages
  const lang = components.languages && components.languages[name];
  if (!lang) { console.error('  ! unknown component: ' + name); return; }
  const req = lang.require;
  const deps = Array.isArray(req) ? req : (req ? [req] : []);
  deps.forEach(resolve);
  resolved.push(name);
}

['core', 'markup', 'css', 'clike', 'javascript'].forEach(resolve);
WANTED.forEach(resolve);

const parts = [];
for (const name of resolved) {
  const f = path.join(prismDir, 'components', 'prism-' + name + '.min.js');
  if (!fs.existsSync(f)) { console.error('  ! missing file for: ' + name); continue; }
  parts.push('/* prism component: ' + name + ' */\n' + fs.readFileSync(f, 'utf8'));
}

fs.mkdirSync(outDir, { recursive: true });
const banner = '/* Prism bundle generated by MacDownLite build_prism.js — components: '
  + resolved.join(', ') + ' */\n';
fs.writeFileSync(path.join(outDir, 'prism.js'), banner + parts.join('\n'));
console.log('prism.js written with ' + resolved.length + ' components: ' + resolved.join(', '));

// Theme CSS: MacDown's default is Prism's stock theme.
const themeSrc = path.join(prismDir, 'themes', 'prism.css');
fs.copyFileSync(themeSrc, path.join(outDir, 'prism.css'));
console.log('prism.css written from themes/prism.css');
